                6'd15: case (mode_f)
                    2'd0: cell_glyph = G_YUN;
                    2'd1: cell_glyph = G_DAO;
                    2'd2: cell_glyph = G_YING2;
                    default: cell_glyph = G_YAN;
                endcase
                6'd16: case (mode_f)
                    2'd0: cell_glyph = G_YING;
                    2'd1: cell_glyph = G_ZHAN;
                    2'd2: cell_glyph = G_JI;
                    default: cell_glyph = G_SHI;
                endcase
                6'd19: cell_glyph = auto_f ? G_PLAY : G_PAUSE;
                // Hex digit d is glyph id d.
                6'd21: case (period_f)
                    2'd0: cell_glyph = 6'd2;
                    2'd1: cell_glyph = 6'd5;
                    2'd2: cell_glyph = 6'd1;
                    default: cell_glyph = 6'd3;
                endcase
                6'd22: cell_glyph = period_f[1] ? 6'd0 : G_S;
                6'd23: cell_glyph = period_f[1] ? G_S : G_BLANK;
                6'd24, 6'd25, 6'd26, 6'd27, 6'd28, 6'd29,
                6'd30, 6'd31, 6'd32, 6'd33, 6'd34, 6'd35:
                    cell_glyph = res_glyph(cell_no);
                6'd36: cell_glyph = fault ? 6'd14 : G_BLANK;
                6'd37: cell_glyph = fault ? {2'b00, error_f[7:4]} : 6'd0;
                6'd38: cell_glyph = fault ? {2'b00, error_f[3:0]} :
                                            {4'd0, index_f} + 6'd1;
                default: cell_glyph = G_BLANK;
            endcase
        end
    endfunction

    reg [23:0] mode_rgb;
    always @(*) begin
        case (mode_f)
            2'd0: mode_rgb = 24'h40E070;
            2'd1: mode_rgb = 24'hFFE14D;
            2'd2: mode_rgb = 24'hFF4040;
            default: mode_rgb = 24'h40A0FF;
        endcase
    end

    // ------------------------------------------------ pixel path
    // Glyph lookup at (x, y); shadow lookup at (x - 2, y - 2).
    wire [11:0] glyph_row = line_y - GLYPH_Y_R;
    wire glyph_rows = (line_y >= GLYPH_Y_R) && (line_y < GLYPH_Y_R + 12'd16);
    wire [5:0] cell_a = pixel_x[9:4];
    wire [5:0] glyph_a = cell_glyph(cell_a);
    wire [9:0] addr_a = {glyph_a, glyph_row[3:0]};

    wire [9:0] shadow_x = pixel_x - 10'd2;
    wire [11:0] shadow_row = line_y - GLYPH_Y_R - 12'd2;
    wire shadow_rows = (line_y >= GLYPH_Y_R + 12'd2) && (line_y < GLYPH_Y_R + 12'd18);
    wire [5:0] glyph_b = cell_glyph(shadow_x[9:4]);
    wire [9:0] addr_b = {glyph_b, shadow_row[3:0]};

    reg [23:0] glyph_rgb;
    always @(*) begin
        if (fault && cell_a >= 6'd36)
            glyph_rgb = ERROR_RGB;
        else if (glyph_a == G_CELL_ON)
            glyph_rgb = CELL_ON_RGB;
        else if (glyph_a == G_CELL_OFF)
            glyph_rgb = CELL_OFF_RGB;
        else if (glyph_a >= G_YUN && glyph_a <= G_SHI)
            glyph_rgb = mode_rgb;
        else
            glyph_rgb = WHITE_RGB;
    end

    reg [15:0] rom_a_q;
    reg [15:0] rom_b_q;
    reg [23:0] rgb_q;
    reg [23:0] glyph_rgb_q;
    reg [3:0] col_a_q;
    reg [3:0] col_b_q;
    reg glyph_ok_q;
    reg shadow_ok_q;
    reg edge_q;
    reg band_q;

    // Plain synchronous reads without reset so the ROM maps onto a BRAM.
    always @(posedge clk) begin
        rom_a_q <= glyph_rom[addr_a];
        rom_b_q <= glyph_rom[addr_b];
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            hsync_out <= 1'b1;
            vsync_out <= 1'b1;
            de_out <= 1'b0;
            pixel_x_out <= 10'd0;
            rgb_q <= 24'd0;
            glyph_rgb_q <= 24'd0;
            col_a_q <= 4'd0;
            col_b_q <= 4'd0;
            glyph_ok_q <= 1'b0;
            shadow_ok_q <= 1'b0;
            edge_q <= 1'b0;
            band_q <= 1'b0;
            line_y <= 12'd0;
            de_q <= 1'b0;
            vs_q <= 1'b1;
            status_d <= 60'd0;
            vol_f <= 3'd0;
            bright_f <= 2'd0;
            mode_f <= 2'd0;
            auto_f <= 1'b0;
            period_f <= 2'd0;
            index_f <= 2'd0;
            error_f <= 8'd0;
            res_w_f <= 20'd0;
            res_h_f <= 20'd0;
        end else begin
            hsync_out <= hsync;
            vsync_out <= vsync;
            de_out <= de;
            pixel_x_out <= pixel_x;
            rgb_q <= rgb_in;
            de_q <= de;
            vs_q <= vsync;
            if (!vsync)
                line_y <= 12'd0;
            else if (de_q && !de)
                line_y <= line_y + 1'b1;

            status_d <= status_in;
            if (frame_start && (status_in == status_d))
                // res_in is {height, width}, so the fields latch height first.
                {vol_f, bright_f, mode_f, auto_f, period_f, index_f,
                 error_f, res_h_f, res_w_f} <= status_in;

            glyph_rgb_q <= glyph_rgb;
            col_a_q <= pixel_x[3:0];
            col_b_q <= shadow_x[3:0];
            glyph_ok_q <= de && glyph_rows;
            shadow_ok_q <= de && shadow_rows && (pixel_x >= 10'd2);
            edge_q <= de && (line_y >= BAR_Y_R) && (line_y < EDGE_END_R);
            band_q <= de && (line_y >= EDGE_END_R) && (line_y < BAR_END_R);
        end
    end

    wire glyph_hit = glyph_ok_q && rom_a_q[4'd15 - col_a_q];
    wire shadow_hit = shadow_ok_q && rom_b_q[4'd15 - col_b_q];
    wire [8:0] band_r = {1'b0, rgb_q[23:16]} + 9'h006;
    wire [8:0] band_g = {1'b0, rgb_q[15:8]} + 9'h019;
    wire [8:0] band_b = {1'b0, rgb_q[7:0]} + 9'h023;
    wire [23:0] band_rgb = {band_r[8:1], band_g[8:1], band_b[8:1]};

    assign rgb_out = edge_q ? EDGE_RGB :
                     glyph_hit ? glyph_rgb_q :
                     shadow_hit ? SHADOW_RGB :
                     band_q ? band_rgb : rgb_q;
endmodule
