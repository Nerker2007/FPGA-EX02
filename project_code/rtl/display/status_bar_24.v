            else if (value[15:12] != 4'd0) bcd_digits = 3'd4;
            else if (value[11:8] != 4'd0) bcd_digits = 3'd3;
            else if (value[7:4] != 4'd0) bcd_digits = 3'd2;
            else bcd_digits = 3'd1;
        end
