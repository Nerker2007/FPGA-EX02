// Audio-video linked melody source for the player. Each loaded image bank
// plays its own six-note arpeggio loop (C-major rise, A-minor, pentatonic,
// low-high swing), so a picture switch is audible as a new melody after a
// short 1.5 kHz cue blip, and the persisted volume setting scales the output.
// The FIFO/valid/ready contract matches hdmi_pcm_tone_fifo so the audio
// packetizer chain is unchanged.
//
// song_mode = 1 (normal-mode operating state) replaces the per-image melody
// with a looping background song (Jasmine Flower, Yangzhou version) read
// from a BRAM note ROM: image switches are ignored (no blip, no restart),
// each note ends in a short silence and
// decays from full to ENV_FLOOR/256 volume. Entering song_mode restarts the
// song; leaving it restarts the per-image melody. The song path uses the
// 16-point sine; its output is checked sample for sample against the score
// by tools/gen_song_rom.py --wav.
//
// arrive / emerg select the scene sounds, which win over the song and the
// per-image melody and ignore image switches:
//   arrive: G5 E5 C5, 0.5 s each with decay and a 20 ms tail gap, then
//           1.5 s silence (6 steps of 0.5 s = 3 s loop).
//   emerg : 960 / 770 Hz alternating every 0.4 s, no decay, no gap, phase
//           continuous across the pitch change.
// Any change of the scene code restarts the counters, phase and envelope
// and drops the cue blip. The per-image melody and the blip read a 256-point
// music-box wave and decay per note with a 20 ms (blip: 10 ms) tail gap.
// The note ROM, its pitch table, SONG_LEN and the wave ROM are generated by
// tools/gen_song_rom.py --write from tools/song_jasmine.txt; do not edit
// the GENERATED regions by hand.
