                    end
                end
            end else if (sample_tick) begin
                overflow <= 1'b1;
            end

            if (sample_pop)
                read_pointer <= read_pointer + 1'b1;

            case ({sample_push, sample_pop})
                2'b10: fifo_count <= fifo_count + 1'b1;
                2'b01: fifo_count <= fifo_count - 1'b1;
                default: fifo_count <= fifo_count;
            endcase

            // Leaving the song or an image switch restarts the per-image
            // melody from its first note; a switch also loads the cue blip.
            // Applied last so they win over the same-edge note advance.
            if (demo_restart) begin
                note_index <= 3'd0;
                note_sample_count <= 15'd0;
                envelope <= 8'd255;
                envelope_step_count <= 12'd0;
            end
            if (media_switch)
                blip_countdown <= BLIP_SAMPLES[12:0];

            // A scene change starts the new sound from its first step, drops
            // any blip and rewinds the melody, so no cue plays on the change.
            if (scene_change) begin
                scene_sub <= 15'd0;
                scene_step <= 3'd0;
                envelope <= 8'd255;
                envelope_step_count <= 12'd0;
                blip_countdown <= 13'd0;
                note_index <= 3'd0;
                note_sample_count <= 15'd0;
            end

            // Entering the song starts it from its first note and drops any
            // unfinished blip.
            if (song_enter) begin
                song_index <= 8'd0;
                sixteenth_sample_count <= 16'd0;
                sixteenth_count <= 4'd0;
                envelope <= 8'd255;
                envelope_step_count <= 12'd0;
                blip_countdown <= 13'd0;
            end
        end
    end
endmodule
